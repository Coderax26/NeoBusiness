/**
 * Frontend plan 01 — gap I-3: single source of truth for API routes.
 *
 * Statically extracts every NestJS route (controller prefix + method decorator) from
 * apps/api/src and writes a typed route table to packages/api-client/src/routes.generated.ts.
 * No DB / running server is required, so it works in CI and offline.
 *
 *   node scripts/generate-api-routes.mjs          # regenerate
 *   node scripts/generate-api-routes.mjs --check  # exit 1 if the checked-in file is stale
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const apiSrc = path.join(root, 'apps/api/src');
export const OUTPUT_FILE = path.join(root, 'packages/api-client/src/routes.generated.ts');

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.name.endsWith('.controller.ts')) out.push(p);
  }
  return out;
}

const join = (...parts) =>
  '/' + parts.filter(Boolean).join('/').split('/').filter(Boolean).join('/');

export function extractRoutes() {
  const routes = [];
  for (const file of walk(apiSrc).sort()) {
    const src = fs.readFileSync(file, 'utf8');
    const ctl = /@Controller\(\s*(?:['"`]([^'"`]*)['"`])?\s*\)/.exec(src);
    if (!ctl) continue;
    const prefix = ctl[1] ?? '';
    const re = /@(Get|Post|Put|Patch|Delete|Sse)\(\s*(?:['"`]([^'"`]*)['"`])?\s*\)/g;
    let m;
    while ((m = re.exec(src))) {
      routes.push({
        method: m[1] === 'Sse' ? 'GET' : m[1].toUpperCase(),
        path: join(prefix, m[2] ?? ''),
        module: path.relative(apiSrc, file).split(path.sep).slice(0, -1).join('/') || 'root',
      });
    }
  }
  const seen = new Set();
  return routes
    .filter((r) => !seen.has(r.method + r.path) && seen.add(r.method + r.path))
    .sort((a, b) => (a.path + a.method).localeCompare(b.path + b.method));
}

export function renderRoutesFile(routes = extractRoutes()) {
  const rows = routes
    .map((r) => `  { method: '${r.method}', path: '${r.path}', module: '${r.module}' },`)
    .join('\n');
  return `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-api-routes.mjs — DO NOT EDIT.
// Source of truth: NestJS controllers in apps/api/src. Global prefix: /api/v1.
export const API_PREFIX = '/api/v1' as const;

export const API_ROUTES = [
${rows}
] as const;

export type ApiRoute = (typeof API_ROUTES)[number];
export type ApiRoutePath = ApiRoute['path'];

/** Convert a route template ("/orders/:id/confirm") to a RegExp matching concrete paths. */
export function routeToRegExp(template: string): RegExp {
  const body = template
    .split('/')
    .map((seg) => (seg.startsWith(':') ? '[^/]+' : seg))
    .join('/');
  return new RegExp('^' + body + '$');
}

/** True when a concrete request path (without /api/v1) matches a known backend route. */
export function isKnownRoute(method: string, concretePath: string): boolean {
  const clean = concretePath.split('?')[0].replace(/\\/+$/, '') || '/';
  return API_ROUTES.some((r) => r.method === method.toUpperCase() && routeToRegExp(r.path).test(clean));
}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = renderRoutesFile();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUTPUT_FILE) ? fs.readFileSync(OUTPUT_FILE, 'utf8').replace(/\r\n/g, '\n') : '';
    if (cur !== next) {
      console.error('routes.generated.ts is stale — run: node scripts/generate-api-routes.mjs');
      process.exit(1);
    }
    console.log('routes.generated.ts is up to date');
  } else {
    fs.writeFileSync(OUTPUT_FILE, next);
    console.log(`Wrote ${OUTPUT_FILE}`);
  }
}
